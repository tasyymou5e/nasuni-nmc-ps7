#Requires -Version 7.4
<#
.SYNOPSIS
    Generates one cmdlet per NMC endpoint from src/Nasuni.Nmc/Data/Endpoints.psd1, and the
    module manifest with an explicit FunctionsToExport list.
.DESCRIPTION
    The output is committed and reviewed like normal code; nothing is generated at runtime.
    Run again whenever Endpoints.psd1 changes. CI fails if the committed output differs.
#>
[CmdletBinding()]
param(
    [string]$ModuleRoot = (Join-Path -Path $PSScriptRoot -ChildPath '../src/Nasuni.Nmc'),
    [string]$ModuleVersion = '0.1.0'
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$manifest = Import-PowerShellDataFile -LiteralPath (Join-Path -Path $ModuleRoot -ChildPath 'Data/Endpoints.psd1')
$skip = @('Login', 'Logout')   # handled by Connect-Nasuni / Disconnect-Nasuni

$verbMap = [ordered]@{
    List = 'Get'; Get = 'Get'; New = 'New'; Add = 'Add'; Update = 'Set'; Remove = 'Remove'
    Block = 'Block'; Unblock = 'Unblock'; Enable = 'Enable'; Disable = 'Disable'
    Request = 'Request'; Refresh = 'Update'; Set = 'Set'
}
$special = @{ BringPathIntoCache = 'Invoke-NasuniCachePath' }

function ConvertTo-Pascal([string]$snake) {
    (($snake -split '_') | ForEach-Object { if ($_.Length) { $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1) } }) -join ''
}
function Get-CmdName($ep) {
    if ($special.ContainsKey($ep.Id)) { return $special[$ep.Id] }
    foreach ($prefix in $verbMap.Keys) {
        if ($ep.Id -cmatch "^$prefix([A-Z].*)$") { return '{0}-Nasuni{1}' -f $verbMap[$prefix], $Matches[1] }
    }
    throw "No verb mapping for endpoint id '$($ep.Id)'."
}
function Format-SingleQuoted([string]$s) { $s -replace "'", "''" }
# DEBUG NOTE (See docs/TROUBLESHOOTING.md, "Generator"):
#  - path -> FolderPath: a parameter named Path with alias 'path' clashes (names ignore case),
#    and the cmdlet then fails to load with MetadataException.
#  - cred_uuid -> CloudCredentialId: the default PascalCase name 'CredUuid' trips
#    PSAvoidUsingPlainTextForPassword. It is an id, not a secret, so that rule is suppressed.
$paramNameMap = @{ cred_uuid = 'CloudCredentialId'; path = 'FolderPath' }

# Work out names, and add a 'List' suffix when a List endpoint collides with a Get endpoint.
$entries = foreach ($ep in $manifest.Endpoints) {
    if ($skip -contains $ep.Id) { continue }
    [pscustomobject]@{ Ep = $ep; Name = Get-CmdName $ep }
}
$groups = $entries | Group-Object Name | Where-Object Count -GT 1
foreach ($g in $groups) {
    foreach ($e in $g.Group) { if ($e.Ep.Id -like 'List*') { $e.Name = $e.Name + 'List' } }
}
$dupes = $entries | Group-Object Name | Where-Object Count -GT 1
if ($dupes) { throw "Unresolved cmdlet name collisions: $($dupes.Name -join ', ')" }

$sb = [System.Text.StringBuilder]::new()
$null = $sb.AppendLine('# <auto-generated> by build/New-EndpointCmdlets.ps1 from Data/Endpoints.psd1. Do not edit by hand. </auto-generated>')
$null = $sb.AppendLine('')

foreach ($e in ($entries | Sort-Object Name)) {
    $ep = $e.Ep
    $isWrite = $ep.Method -ne 'GET'
    $impact = if ($ep.Destructive) { 'High' } else { 'Medium' }
    $binding = if ($isWrite) { "[CmdletBinding(SupportsShouldProcess, ConfirmImpact = '$impact')]" } else { '[CmdletBinding()]' }
    $suppress = if ($e.Name -match 's(List)?$' -or $e.Name -match 'Settings') { "    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSUseSingularNouns', '', Justification = 'Mirrors the NMC API resource name')]`n" } else { '' }
    if ($ep.PathParams -contains 'cred_uuid') { $suppress += "    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSAvoidUsingPlainTextForPassword', 'CloudCredentialId', Justification = 'An identifier (UUID) of a cloud credential, not a secret')]`n" }
    if ($isWrite) { $suppress += "    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSShouldProcess', '', Justification = 'ShouldProcess is invoked once via Invoke-NmcEndpoint -Cmdlet `$PSCmdlet')]`n" }

    $help = [System.Collections.Generic.List[string]]::new()
    $help.Add('    <#')
    $help.Add('    .SYNOPSIS')
    $help.Add("        $($ep.Summary)")
    $help.Add('    .DESCRIPTION')
    $help.Add("        NMC API v1.2: $($ep.Method) $($ep.Path)")
    if ($ep.Paged) { $help.Add('        Returns every item, paging automatically. Use -First to stop early.') }
    if ($ep.Async) { $help.Add('        Asynchronous: returns an NMC message. Use -Wait to block until it is synced.') }
    if ($ep.Destructive) { $help.Add('        DESTRUCTIVE: asks for confirmation (ConfirmImpact High). Use -WhatIf to preview.') }

    $params = [System.Collections.Generic.List[string]]::new()
    $pathMap = [System.Collections.Generic.List[string]]::new()
    foreach ($pp in $ep.PathParams) {
        $pn = if ($paramNameMap.ContainsKey($pp)) { $paramNameMap[$pp] } else { ConvertTo-Pascal $pp }
        $help.Add(".PARAMETER $pn".PadLeft(".PARAMETER $pn".Length + 4))
        $help.Add("        Value for {$pp} in the request path.")
        $params.Add("        [Parameter(Mandatory, ValueFromPipelineByPropertyName)][Alias('$pp')][ValidateNotNullOrEmpty()][string]`$$pn")
        $pathMap.Add("'$pp' = `$$pn")
    }

    $queryMap = [System.Collections.Generic.List[string]]::new()
    foreach ($qp in $ep.QueryParams) {
        if ($qp -in @('limit', 'offset')) { continue }
        $qn = ConvertTo-Pascal $qp
        if ($ep.Id -eq 'RemoveAntivirusViolation' -and $qp -eq 'action') {
            # No default: the caller must choose explicitly (the old script defaulted to delete_file).
            $params.Add("        [Parameter(Mandatory)][ValidateSet('delete_file', 'ignore_violation')][string]`$$qn")
        }
        else {
            $params.Add("        [string]`$$qn")
        }
        $help.Add("    .PARAMETER $qn")
        $help.Add("        Query parameter '$qp'.")
        $queryMap.Add("'$qp' = `$$qn")
    }

    $callExtra = ''
    if ($ep.Method -eq 'GET' -and $ep.Paged) {
        $params.Add('        [ValidateRange(0, [int]::MaxValue)][int]$First = 0')
        $params.Add('        [ValidateRange(1, 1000)][int]$PageSize = 200')
        $help.Add('    .PARAMETER First'); $help.Add('        Stop after this many items (0 = all).')
        $help.Add('    .PARAMETER PageSize'); $help.Add('        Items per API page (1-1000).')
        $callExtra = ' -First $First -PageSize $PageSize'
    }
    if ($isWrite) {
        $params.Add('        [object]$Body')
        $help.Add('    .PARAMETER Body'); $help.Add('        Request body (hashtable or object), serialized with ConvertTo-Json.')
        $callExtra += ' -Body $Body -HasBody:$PSBoundParameters.ContainsKey(''Body'')'
        if ($ep.Async) {
            $params.Add('        [switch]$Wait')
            $params.Add('        [int]$TimeoutSeconds = 300')
            $help.Add('    .PARAMETER Wait'); $help.Add('        Wait for the NMC message to reach synced (throws on failure).')
            $help.Add('    .PARAMETER TimeoutSeconds'); $help.Add('        Maximum wait, clamped to 1-3600 seconds.')
            $callExtra += ' -Wait:$Wait -TimeoutSeconds $TimeoutSeconds'
        }
    }
    $help.Add('    .LINK')
    $help.Add("        $($ep.DocUrl)")
    $help.Add('    #>')

    $null = $sb.AppendLine("function $($e.Name) {")
    $null = $sb.AppendLine(($help | ForEach-Object { $_ -replace '^\s*\.PARAMETER', '    .PARAMETER' }) -join "`n")
    $null = $sb.Append($suppress)
    $null = $sb.AppendLine("    $binding")
    $null = $sb.AppendLine('    param(')
    $null = $sb.AppendLine(($params -join ",`n"))
    $null = $sb.AppendLine('    )')
    $null = $sb.AppendLine('    process {')
    $null = $sb.AppendLine("        Invoke-NmcEndpoint -Id '$(Format-SingleQuoted $ep.Id)' -Cmdlet `$PSCmdlet -PathValues @{ $($pathMap -join '; ') } -Query @{ $($queryMap -join '; ') }$callExtra")
    $null = $sb.AppendLine('    }')
    $null = $sb.AppendLine('}')
    $null = $sb.AppendLine('')
}

$outFile = Join-Path -Path $ModuleRoot -ChildPath 'Public/Endpoints.Generated.ps1'
[System.IO.File]::WriteAllText($outFile, $sb.ToString().Replace("`r`n", "`n"), [System.Text.UTF8Encoding]::new($false))

$handWritten = @(
    'Connect-Nasuni', 'Disconnect-Nasuni', 'Get-NasuniConnection', 'Invoke-NasuniRequest', 'Wait-NasuniMessage',
    'Test-NasuniNmcTls', 'Test-NasuniFipsHost', 'Assert-NasuniFipsHost', 'Get-NasuniVaultCredential', 'Get-NasuniVaultSecret', 'New-NasuniVaultPkiCertificate', 'Protect-NasuniSensitiveData',
    'New-NasuniBulkItem', 'New-NasuniBulkPlan', 'Export-NasuniBulkPlan', 'Import-NasuniBulkPlan', 'Invoke-NasuniBulkPlan', 'Read-NasuniBulkJournal',
    'Get-NasuniReportList', 'Get-NasuniReport', 'Export-NasuniReport', 'Export-NasuniReportBundle',
    'New-NasuniSharePropertyPlan', 'New-NasuniExportPropertyPlan', 'New-NasuniShareCreatePlan', 'New-NasuniShareDeletePlan', 'New-NasuniShareReplicationPlan',
    'New-NasuniSharePermissionPlan', 'New-NasuniExportCreatePlan', 'New-NasuniExportHostOptionPlan', 'New-NasuniAntivirusPlan', 'New-NasuniClientBlockPlan',
    'Get-NasuniRansomwareAttackIp', 'New-NasuniMessageCleanupPlan', 'New-NasuniGlobalLockPlan', 'New-NasuniFolderQuotaPlan', 'New-NasuniVolumeAuditPlan',
    'Test-NasuniUnprotectedDataAlert', 'Set-NasuniLogging', 'Get-NasuniDiagnostic', 'Import-NasuniCertificate'
)
$exports = @($handWritten) + @($entries.Name | Sort-Object)
$exportText = ($exports | ForEach-Object { "        '$_'" }) -join ",`n"

$psd1 = @"
@{
    RootModule           = 'Nasuni.Nmc.psm1'
    ModuleVersion        = '$ModuleVersion'
    GUID                 = '6b0e5a8f-2c1d-4b8e-9a51-3f7d2e9c4a10'
    Description          = 'PowerShell 7 client for the Nasuni Management Console API v1.2: validated TLS, FIPS-mode host enforcement, Vault-sourced credentials, rate limiting, paging and async message handling.'
    PowerShellVersion    = '7.4'
    CompatiblePSEditions = @('Core')
    FunctionsToExport    = @(
$exportText
    )
    CmdletsToExport      = @()
    VariablesToExport    = @()
    AliasesToExport      = @()
    PrivateData          = @{
        PSData = @{
            Tags       = @('Nasuni', 'NMC', 'FIPS', 'API')
            LicenseUri = 'https://opensource.org/licenses/MIT'
        }
    }
}
"@
[System.IO.File]::WriteAllText((Join-Path -Path $ModuleRoot -ChildPath 'Nasuni.Nmc.psd1'), $psd1.Replace("`r`n", "`n"), [System.Text.UTF8Encoding]::new($false))

Write-Output "Generated $($entries.Count) endpoint cmdlets; exported $($exports.Count) functions."
